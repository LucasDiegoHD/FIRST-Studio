import type { CiprixProject } from "../../schema/ciprix-project";
import {
  formatDouble,
  requestToCommandMethod,
  toCamelCase,
  toPackageSegment,
  toPascalCase,
  xboxButtonToJavaMethod,
} from "../java-utils";
import { getVendorIoClassName, type GeneratedFile } from "../subsystems/roller";

export function generateCoreRobotFiles(project: CiprixProject): GeneratedFile[] {
  const pkg = project.project.packageName;
  const pkgPath = pkg.replace(/\./g, "/");
  const javaBase = `src/main/java/${pkgPath}`;

  const mainJava = `package ${pkg};

import edu.wpi.first.wpilibj.RobotBase;

/** Entry point. Initialization lives in {@link Robot}. */
public final class Main {
  private Main() {}

  public static void main(String... args) {
    RobotBase.startRobot(Robot::new);
  }
}
`;

  const constantsJava = `package ${pkg};

import edu.wpi.first.wpilibj.DriverStation.Alliance;
import org.ciprix.CiprixSettings.Mode;

/** Robot-wide constants generated by FIRST Studio. */
public final class Constants {
  private Constants() {}

  /** What runs off-robot: {@link Mode#SIM} (physics simulation) or {@link Mode#REPLAY}. */
  public static final Mode simMode = Mode.${project.project.simMode};

  /** Live-tunable values on the dashboard. Turn off at competitions. */
  public static final boolean tuningMode = ${project.project.tuningMode};

  public static final double CONTROLLER_DEADBAND = ${formatDouble(project.project.controllerDeadband)};

  /** Alliance assumed when neither the FMS nor the Driver Station provides one. */
  public static final Alliance DEFAULT_ALLIANCE = Alliance.${project.project.defaultAlliance};

  public static final double FIELD_LENGTH_METERS = ${formatDouble(project.project.fieldLengthMeters)};

  public static final double FIELD_WIDTH_METERS = ${formatDouble(project.project.fieldWidthMeters)};

  /** What the driver asks the robot to do. */
  public enum RobotRequest {
${project.superstructure.requests.map((r) => `    ${r}`).join(",\n")}
  }

  /** States of the overall state machine (the SuperStructure). */
  public enum RobotState {
${project.superstructure.states.map((s) => `    ${s}`).join(",\n")}
  }
}
`;

  const robotJava = `package ${pkg};

import edu.wpi.first.wpilibj2.command.Command;
import org.ciprix.CiprixRobot;
import org.ciprix.CiprixSettings;

/** Robot lifecycle entry point extending {@link CiprixRobot}. */
public class Robot extends CiprixRobot {
  private final RobotContainer robotContainer;

  public Robot() {
    super(Constants.simMode, Constants.tuningMode);
    robotContainer = new RobotContainer();
  }

  @Override
  protected void configure() {
    CiprixSettings.setControllerDeadband(Constants.CONTROLLER_DEADBAND);
    CiprixSettings.setDefaultAlliance(Constants.DEFAULT_ALLIANCE);
    CiprixSettings.setFieldSize(Constants.FIELD_LENGTH_METERS, Constants.FIELD_WIDTH_METERS);
  }

  @Override
  protected Command getAutonomousCommand() {
    return robotContainer.getAutonomousCommand();
  }
}
`;

  // SuperStructure.java
  const subInfos = project.subsystems.map((s) => {
    const className = toPascalCase(s.name);
    const varName = toCamelCase(className);
    const subPkg = toPackageSegment(s.name);
    const requestEnum = `${className}Request`;
    const requestField = `${varName}Request`;
    return {
      sub: s,
      className,
      varName,
      subPkg,
      requestEnum,
      requestField,
    };
  });

  const superImports = subInfos
    .flatMap((info) => [
      `import ${pkg}.subsystems.${info.subPkg}.${info.className};`,
      `import ${pkg}.subsystems.${info.subPkg}.${info.className}Constants.${info.requestEnum};`,
    ])
    .sort()
    .join("\n");

  const superFields = subInfos
    .map(
      (info) =>
        `  private final ${info.className} ${info.varName};\n  private ${info.requestEnum} ${info.requestField} = ${info.requestEnum}.${info.sub.fsm.initialRequest};`,
    )
    .join("\n");

  const ctorParams = subInfos.map((info) => `${info.className} ${info.varName}`).join(", ");
  const ctorAssigns = subInfos.map((info) => `    this.${info.varName} = ${info.varName};`).join("\n");

  const superStates = project.superstructure.states
    .map((stateName) => {
      const actionsForState = project.superstructure.stateActions[stateName] ?? {};
      const assignments = subInfos.map((info) => {
        const targetReq = actionsForState[info.sub.id] ?? info.sub.fsm.initialRequest;
        return `${info.requestField} = ${info.requestEnum}.${targetReq};`;
      });
      if (assignments.length === 0) {
        return `    generalFsm.state(RobotState.${stateName}).onEnter(() -> {});`;
      }
      if (assignments.length === 1) {
        return `    generalFsm.state(RobotState.${stateName}).onEnter(() -> ${assignments[0].replace(/;$/, "")});`;
      }
      return `    generalFsm\n        .state(RobotState.${stateName})\n        .onEnter(\n            () -> {\n${assignments.map((a) => `              ${a}`).join("\n")}\n            });`;
    })
    .join("\n");

  const superBindings = project.superstructure.bindings
    .map((b) => `    bindRequest(RobotRequest.${b.request}, RobotState.${b.entryState});`)
    .join("\n");

  const superGetters = subInfos
    .map(
      (info) => `  public ${info.requestEnum} get${info.className}Request() {
    return ${info.requestField};
  }

  public boolean is${info.className}AtGoal() {
    return ${info.varName}.atGoal();
  }`,
    )
    .join("\n\n");

  const superStructureJava = `package ${pkg}.subsystems.superstructure;

import ${pkg}.Constants.RobotRequest;
import ${pkg}.Constants.RobotState;
${superImports ? superImports + "\n" : ""}import org.ciprix.interfaces.subsystem.SuperStructureBase;

/** Overall robot state machine coordinating subsystems. */
public class SuperStructure extends SuperStructureBase<RobotRequest, RobotState> {
${superFields ? "\n" + superFields + "\n" : ""}
  public SuperStructure(${ctorParams}) {
    super(
        "Subsystems/SuperStructure",
        RobotState.class,
        RobotState.${project.superstructure.initialState},
        RobotRequest.${project.superstructure.initialRequest});
${ctorAssigns ? ctorAssigns + "\n" : ""}
${superStates}

${superBindings}
    generalFsm.validateComplete();
  }
${superGetters ? "\n" + superGetters + "\n" : ""}}
`;

  // SuperStructureCommands.java
  const pilotEntries = project.controls.pilotPriority;
  const usedParamNames = new Set<string>();
  const pilotParams = pilotEntries.map((entry, idx) => {
    const base = `${toCamelCase(entry.request)}Button`;
    let paramName = base;
    if (usedParamNames.has(paramName)) {
      paramName = `${base}${idx + 1}`;
    }
    usedParamNames.add(paramName);
    return { ...entry, paramName };
  });

  const manageParamsSignature = [
    "SuperStructure superStructure",
    ...pilotParams.map((p) => `BooleanSupplier ${p.paramName}`),
  ].join(", ");

  let requestSelectionBody = `              RobotRequest request = RobotRequest.${project.superstructure.initialRequest};`;
  if (pilotParams.length > 0) {
    const branches = pilotParams
      .map(
        (p, idx) =>
          `              ${idx === 0 ? "if" : "} else if"} (${p.paramName}.getAsBoolean()) {\n                request = RobotRequest.${p.request};`,
      )
      .join("\n");
    requestSelectionBody = `              RobotRequest request;\n${branches}\n              } else {\n                request = RobotRequest.${project.superstructure.initialRequest};\n              }`;
  }

  const booleanSupplierImport =
    pilotParams.length > 0 ? "import java.util.function.BooleanSupplier;\n" : "";

  const superStructureCommandsJava = `package ${pkg}.commands;

import edu.wpi.first.wpilibj2.command.Command;
import edu.wpi.first.wpilibj2.command.Commands;
import ${pkg}.Constants.RobotRequest;
import ${pkg}.subsystems.superstructure.SuperStructure;
${booleanSupplierImport}
/** Driver commands for the SuperStructure. */
public final class SuperStructureCommands {
  private SuperStructureCommands() {}

  /** Evaluates the pilot's button priorities every cycle and forwards the winning request. */
  public static Command manageRequests(${manageParamsSignature}) {
    return Commands.run(
            () -> {
${requestSelectionBody}
              superStructure.setRequest(request);
            },
            superStructure)
        .withName("Requests by pilot");
  }
}
`;

  // RobotContainer.java
  const containerImports = [
    `import edu.wpi.first.wpilibj.smartdashboard.SmartDashboard;`,
    `import edu.wpi.first.wpilibj2.command.Command;`,
    `import edu.wpi.first.wpilibj2.command.Commands;`,
    `import edu.wpi.first.wpilibj2.command.button.CommandXboxController;`,
    `import ${pkg}.commands.SuperStructureCommands;`,
    `import ${pkg}.subsystems.superstructure.SuperStructure;`,
    `import org.ciprix.CiprixSettings;`,
    ...subInfos.flatMap((info) => {
      const vendorIo = getVendorIoClassName(info.sub.name, info.sub.motor.vendor);
      return [
        `import ${pkg}.subsystems.${info.subPkg}.${info.className};`,
        `import ${pkg}.subsystems.${info.subPkg}.${info.className}Commands;`,
        `import ${pkg}.subsystems.${info.subPkg}.${info.className}IO;`,
        `import ${pkg}.subsystems.${info.subPkg}.${info.className}IOSim;`,
        `import ${pkg}.subsystems.${info.subPkg}.${vendorIo};`,
      ];
    }),
  ];

  const subById = new Map(subInfos.map((info) => [info.sub.id, info]));

  const containerFields = [
    ...subInfos.map((info) => `  private final ${info.className} ${info.varName};`),
    `  private final SuperStructure superStructure;`,
  ].join("\n");

  const containerInits = subInfos
    .map((info) => {
      const vendorIo = getVendorIoClassName(info.sub.name, info.sub.motor.vendor);
      return `    ${info.varName} =
        new ${info.className}(
            switch (CiprixSettings.getMode()) {
              case REAL -> new ${vendorIo}();
              case SIM -> new ${info.className}IOSim();
              case REPLAY -> new ${info.className}IO() {};
            });`;
    })
    .join("\n");

  const superArgs = subInfos.map((info) => info.varName).join(", ");
  const pilotArgs = [
    "superStructure",
    ...pilotParams.map((p) => `pilot.${xboxButtonToJavaMethod(p.button)}`),
  ].join(", ");

  const defaultCommands = subInfos
    .map(
      (info) =>
        `    ${info.varName}.setDefaultCommand(${info.className}Commands.defaultCommand(superStructure, ${info.varName}));`,
    )
    .join("\n");

  const copilotBindings = project.controls.copilotOverrides
    .map((ov) => {
      const info = subById.get(ov.subsystemId);
      if (!info) return null;
      const cmdMethod = requestToCommandMethod(ov.request);
      return `    copilot.${xboxButtonToJavaMethod(ov.button)}.whileTrue(${info.className}Commands.${cmdMethod}(${info.varName}));`;
    })
    .filter(Boolean)
    .join("\n");

  const selfTests = subInfos
    .filter((info) => info.sub.selfTest.enabled)
    .map(
      (info) =>
        `    SmartDashboard.putData("SelfTest/${info.className}", ${info.varName}.selfTestCommand());`,
    )
    .join("\n");

  const driveContextComment = project.features.driveContextStub
    ? "\n    // DriveContext stub enabled: integrate Phoenix Tuner X or YAGSL drivetrain here."
    : "";

  const robotContainerJava = `package ${pkg};

${containerImports.sort().join("\n")}

/** Robot structure: subsystems, driver and co-driver buttons, autonomous. */
public class RobotContainer {
${containerFields}

  private final CommandXboxController pilot = new CommandXboxController(0);
  private final CommandXboxController copilot = new CommandXboxController(1);

  public RobotContainer() {
${containerInits ? containerInits + "\n" : ""}    superStructure = new SuperStructure(${superArgs});

    configureBindings();
  }

  private void configureBindings() {
    superStructure.setDefaultCommand(
        SuperStructureCommands.manageRequests(${pilotArgs}));
${defaultCommands ? "\n" + defaultCommands : ""}
${copilotBindings ? "\n" + copilotBindings : ""}
${selfTests ? "\n" + selfTests : ""}${driveContextComment}
  }

  public Command getAutonomousCommand() {
    return Commands.none();
  }
}
`;

  const wpilibPrefs = JSON.stringify(
    {
      enableCppIntellisense: false,
      currentLanguage: "java",
      projectYear: String(project.project.year),
      teamNumber: project.project.teamNumber,
    },
    null,
    4,
  ) + "\n";

  const rootProjectName = project.project.name.replace(/[^A-Za-z0-9_-]/g, "-") || "first-robot";
  const settingsGradle = `import org.gradle.internal.os.OperatingSystem

pluginManagement {
    repositories {
        mavenLocal()
        gradlePluginPortal()
        String frcYear = '${project.project.year}'
        File frcHome
        if (OperatingSystem.current().isWindows()) {
            String publicFolder = System.getenv('PUBLIC')
            if (publicFolder == null) {
                publicFolder = "C:\\\\Users\\\\Public"
            }
            def homeRoot = new File(publicFolder, "wpilib")
            frcHome = new File(homeRoot, frcYear)
        } else {
            def userFolder = System.getProperty("user.home")
            def homeRoot = new File(userFolder, "wpilib")
            frcHome = new File(homeRoot, frcYear)
        }
        def frcHomeMaven = new File(frcHome, 'maven')
        maven {
            name = 'frcHome'
            url = frcHomeMaven
        }
    }
}

Properties props = System.getProperties();
props.setProperty("org.gradle.internal.native.headers.unresolved.dependencies.ignore", "true");

rootProject.name = '${rootProjectName}'

def ciprixDir = file('../..')
def ciprixSettings = new File(ciprixDir, 'settings.gradle')
if (ciprixSettings.exists() && ciprixSettings.text.contains("rootProject.name = 'ciprix'")) {
    includeBuild(ciprixDir)
}
`;

  return [
    { path: `${javaBase}/Main.java`, content: mainJava },
    { path: `${javaBase}/Constants.java`, content: constantsJava },
    { path: `${javaBase}/Robot.java`, content: robotJava },
    { path: `${javaBase}/subsystems/superstructure/SuperStructure.java`, content: superStructureJava },
    { path: `${javaBase}/commands/SuperStructureCommands.java`, content: superStructureCommandsJava },
    { path: `${javaBase}/RobotContainer.java`, content: robotContainerJava },
    { path: `.wpilib/wpilib_preferences.json`, content: wpilibPrefs },
    { path: `settings.gradle`, content: settingsGradle },
    { path: `ciprix-project.json`, content: JSON.stringify(project, null, 2) + "\n" },
  ];
}
