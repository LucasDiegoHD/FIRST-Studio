function escapeJavaString(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n");
}

function hexToJavaColor(hex?: string): string {
  if (!hex || !/^#[0-9a-fA-F]{6}$/.test(hex)) return "Color.kBlack";
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return `new Color(${r}, ${g}, ${b})`;
}

function ledPatternToJavaEnum(pattern: LedPattern): string {
  switch (pattern) {
    case "solid":
      return "LedPattern.SOLID";
    case "blink":
      return "LedPattern.BLINK";
    case "breathe":
      return "LedPattern.BREATHE";
    case "rainbow":
      return "LedPattern.RAINBOW";
    case "progressBar":
      return "LedPattern.PROGRESS_BAR";
    case "alliance":
      return "LedPattern.ALLIANCE";
  }
}

function renderRumbleSupplierExpr(
  targetVar: string,
  action: Extract<StateAction, { kind: "rumble" }> | Extract<SuperStateEffect, { kind: "rumble" }>,
): string {
  const pattern: RumblePattern = action.pattern;
  switch (pattern) {
    case "continuous":
      return `() -> ${targetVar}.continuous(${formatDouble(action.intensity)}, ${formatDouble(action.lightIntensity ?? action.intensity)}, ${formatDouble(action.seconds)}, false)`;
    case "pulses":
      return `() -> ${targetVar}.pulses(${formatDouble(action.intensity)}, ${action.pulseCount ?? 3}, ${formatDouble(action.seconds)})`;
    case "zigZag":
      return `() -> ${targetVar}.zigZag(${formatDouble(action.intensity)}, ${formatDouble(action.seconds)})`;
    case "rampUp":
      return `() -> ${targetVar}.rampUp(${formatDouble(action.intensity)}, ${formatDouble(action.seconds)})`;
    case "lightConfirm":
      return `() -> ${targetVar}.lightConfirm()`;
    case "heavyWarning":
      return `() -> ${targetVar}.heavyWarning()`;
  }
}

function controllerToJavaEnum(controller: "pilot" | "copilot" | "both"): string {
  if (controller === "pilot") return "TargetController.PILOT";
  if (controller === "copilot") return "TargetController.COPILOT";
  return "TargetController.BOTH";
}

function renderLambdaBody(statements: string[], emptyFallback = "() -> {}"): string {
  if (statements.length === 0) return emptyFallback;
  if (statements.length === 1) {
    return `() -> ${statements[0].replace(/;$/, "")}`;
  }
  return `() -> {\n${statements.map((s) => `              ${s}`).join("\n")}\n            }`;
}

export function generateCoreRobotFiles(project: CiprixProject): GeneratedFile[] {
  const pkg = project.project.packageName;
  const pkgPath = pkg.replace(/\./g, "/");
  const javaBase = `src/main/java/${pkgPath}`;

  const mainJava = `package ${pkg};

import edu.wpi.first.wpilibj.RobotBase;

/** Entry point. Initialization lives in {@link Robot}. */
public final class Main {
  private Main() {}

  public static void main(String... args) {
    RobotBase.startRobot(Robot::new);
  }
}
`;

  const constantsJava = `package ${pkg};

import edu.wpi.first.wpilibj.DriverStation.Alliance;
import org.ciprix.CiprixSettings.Mode;

/** Robot-wide constants generated by FIRST Studio. */
public final class Constants {
  private Constants() {}

  /** What runs off-robot: {@link Mode#SIM} (physics simulation) or {@link Mode#REPLAY}. */
  public static final Mode simMode = Mode.${project.project.simMode};

  /** Live-tunable values on the dashboard. Turn off at competitions. */
  public static final boolean tuningMode = ${project.project.tuningMode};

  public static final double CONTROLLER_DEADBAND = ${formatDouble(project.project.controllerDeadband)};

  /** Alliance assumed when neither the FMS nor the Driver Station provides one. */
  public static final Alliance DEFAULT_ALLIANCE = Alliance.${project.project.defaultAlliance};

  public static final double FIELD_LENGTH_METERS = ${formatDouble(project.project.fieldLengthMeters)};

  public static final double FIELD_WIDTH_METERS = ${formatDouble(project.project.fieldWidthMeters)};

  /** What the driver asks the robot to do. */
  public enum RobotRequest {
${project.superstructure.requests.map((r) => `    ${r}`).join(",\n")}
  }

  /** States of the overall state machine (the SuperStructure). */
  public enum RobotState {
${project.superstructure.states.map((s) => `    ${s}`).join(",\n")}
  }
}
`;

  const robotJava = `package ${pkg};

import edu.wpi.first.wpilibj2.command.Command;
import org.ciprix.CiprixRobot;
import org.ciprix.CiprixSettings;

/** Robot lifecycle entry point extending {@link CiprixRobot}. */
public class Robot extends CiprixRobot {
  private final RobotContainer robotContainer;

  public Robot() {
    super(Constants.simMode, Constants.tuningMode);
    robotContainer = new RobotContainer();
  }

  @Override
  protected void configure() {
    CiprixSettings.setControllerDeadband(Constants.CONTROLLER_DEADBAND);
    CiprixSettings.setDefaultAlliance(Constants.DEFAULT_ALLIANCE);
    CiprixSettings.setFieldSize(Constants.FIELD_LENGTH_METERS, Constants.FIELD_WIDTH_METERS);
  }

  @Override
  protected Command getAutonomousCommand() {
    return robotContainer.getAutonomousCommand();
  }
}
`;

  // SuperStructure.java (only motor subsystems!)
  const motorSubs = project.subsystems.filter(isMotorSubsystem);
  const ledSubs = project.subsystems.filter(isLedSubsystem);
  const zones = project.zones ?? [];
  const hasZones = zones.length > 0;
  const dt = project.drivetrain;
  const hasDrivetrain = Boolean(dt?.enabled);
  const zonesWired = hasZones && hasDrivetrain;
  const zoneEnumById = resolveZoneEnumNames(zones);
  const superUsesZones =
    zonesWired &&
    (project.superstructure.transitions ?? []).some(
      (tr) => tr.condition === "inZone" || tr.condition === "outOfZone",
    );

  const subInfos = motorSubs.map((s) => {
    const className = toPascalCase(s.name);
    const varName = toCamelCase(className);
    const subPkg = toPackageSegment(s.name);
    const requestEnum = `${className}Request`;
    const stateEnum = `${className}State`;
    const requestField = `${varName}Request`;
    return {
      sub: s,
      className,
      varName,
      subPkg,
      requestEnum,
      stateEnum,
      requestField,
    };
  });

  const subInfoById = new Map(subInfos.map((info) => [info.sub.id, info]));

  const superImportsList = subInfos.flatMap((info) => [
    `import ${pkg}.subsystems.${info.subPkg}.${info.className};`,
    `import ${pkg}.subsystems.${info.subPkg}.${info.className}Constants.${info.requestEnum};`,
  ]);

  interface SuperAlert {
    fieldName: string;
    message: string;
    level: "INFO" | "WARNING" | "ERROR";
  }
  const superAlerts: SuperAlert[] = [];
  const seenSuperAlertFields = new Set<string>();
  let superHasLogs = false;
  let superHasAlerts = false;

  const superStates = project.superstructure.states
    .map((stateName) => {
      const actionsForState = project.superstructure.stateActions[stateName] ?? {};
      const enterStmts: string[] = subInfos.map((info) => {
        const targetReq = actionsForState[info.sub.id] ?? info.sub.fsm.initialRequest;
        return `${info.requestField} = ${info.requestEnum}.${targetReq};`;
      });
      const periodicStmts: string[] = [];
      const exitStmts: string[] = [];
      const autoClearAlerts: string[] = [];

      const effects = project.superstructure.stateEffects?.[stateName] ?? [];
      for (const eff of effects) {
        if (eff.kind !== "log") continue;
        superHasLogs = true;
        const targetList =
          eff.when === "enter"
            ? enterStmts
            : eff.when === "periodic"
              ? periodicStmts
              : exitStmts;
        targetList.push(
          `Logger.recordOutput("SuperStructure/${escapeJavaString(eff.key)}", "${escapeJavaString(eff.message)}");`,
        );
        if (eff.alertOnDriverStation) {
          superHasAlerts = true;
          const fieldName = `${toCamelCase(`${stateName}_${eff.key}_${superAlerts.length}`)}Alert`;
          if (!seenSuperAlertFields.has(fieldName)) {
            seenSuperAlertFields.add(fieldName);
            superAlerts.push({
              fieldName,
              message: eff.message,
              level: eff.level.toUpperCase() as "INFO" | "WARNING" | "ERROR",
            });
          }
          targetList.push(`${fieldName}.set(true);`);
          if (eff.when !== "exit") {
            autoClearAlerts.push(`${fieldName}.set(false);`);
          }
        }
      }

      for (const clearStmt of autoClearAlerts) {
        if (!exitStmts.includes(clearStmt)) exitStmts.push(clearStmt);
      }

      const localTransitions = (project.superstructure.transitions ?? []).filter(
        (tr) => tr.fromState === stateName,
      );
      const trChains = localTransitions.map((tr) => {
        if (tr.condition === "afterSeconds") {
          return `\n        .transitionAfter(${formatDouble(tr.seconds ?? 1.0)}, RobotState.${tr.toState})`;
        }
        if (tr.condition === "sensorTrue" || tr.condition === "sensorFalse") {
          const info = tr.sensorOwnerId ? subInfoById.get(tr.sensorOwnerId) : undefined;
          const sensor = info?.sub.sensors?.find((s) => s.id === tr.sensorId);
          if (info && sensor) {
            const call = `${info.varName}.${getSensorGetterName(sensor)}()`;
            const expr = tr.condition === "sensorFalse" ? `!${call}` : call;
            return `\n        .transitionTo(RobotState.${tr.toState}, () -> ${expr})`;
          }
          return `\n        .transitionTo(RobotState.${tr.toState}, () -> false)`;
        }
        if (tr.condition === "inZone" || tr.condition === "outOfZone") {
          const zEnum = tr.zoneId ? zoneEnumById.get(tr.zoneId) : undefined;
          if (superUsesZones && zEnum) {
            const call = `fieldZones.inZone(ZoneId.${zEnum}, poseSupplier.get())`;
            const expr = tr.condition === "outOfZone" ? `!${call}` : call;
            return `\n        .transitionTo(RobotState.${tr.toState}, () -> ${expr})`;
          }
          return `\n        .transitionTo(RobotState.${tr.toState}, () -> false)`;
        }
        const ids =
          tr.condition === "allAtGoal"
            ? motorSubs.map((s) => s.id)
            : (tr.subsystemIds ?? []);
        const checks = ids
          .map((id) => subInfoById.get(id))
          .filter((info): info is NonNullable<typeof info> => Boolean(info))
          .map((info) => `is${info.className}AtGoal()`);
        const condExpr = checks.length > 0 ? checks.join(" && ") : "true";
        return `\n        .transitionTo(RobotState.${tr.toState}, () -> ${condExpr})`;
      });
      const chainSuffix = trChains.join("");
      const updateChain =
        periodicStmts.length > 0
          ? `\n        .onUpdate(${renderLambdaBody(periodicStmts)})`
          : "";
      const exitChain =
        exitStmts.length > 0 ? `\n        .onExit(${renderLambdaBody(exitStmts)})` : "";

      if (enterStmts.length === 0 && !updateChain && !exitChain) {
        return `    generalFsm.state(RobotState.${stateName}).onEnter(() -> {})${chainSuffix};`;
      }
      if (enterStmts.length === 1 && !updateChain && !exitChain && trChains.length === 0) {
        return `    generalFsm.state(RobotState.${stateName}).onEnter(() -> ${enterStmts[0].replace(/;$/, "")});`;
      }
      if (enterStmts.length === 1 && !updateChain && !exitChain) {
        return `    generalFsm\n        .state(RobotState.${stateName})\n        .onEnter(() -> ${enterStmts[0].replace(/;$/, "")})${chainSuffix};`;
      }
      return `    generalFsm\n        .state(RobotState.${stateName})\n        .onEnter(\n            ${renderLambdaBody(enterStmts)})${updateChain}${exitChain}${chainSuffix};`;
    })
    .join("\n");

  if (superHasAlerts) {
    superImportsList.push("import org.ciprix.util.PersistentAlert;");
  }
  if (superHasLogs) {
    superImportsList.push("import org.littletonrobotics.junction.Logger;");
  }
  if (superUsesZones) {
    superImportsList.push(
      "import edu.wpi.first.math.geometry.Pose2d;",
      "import java.util.function.Supplier;",
      `import ${pkg}.field.FieldZones;`,
      `import ${pkg}.field.FieldZones.ZoneId;`,
    );
  }

  const superImports = [
    `import ${pkg}.Constants.RobotRequest;`,
    `import ${pkg}.Constants.RobotState;`,
    "import org.ciprix.interfaces.subsystem.SuperStructureBase;",
    ...superImportsList,
  ]
    .sort()
    .join("\n");

  const superAlertFields = superAlerts.map(
    (a) =>
      `  private final PersistentAlert ${a.fieldName} =\n      new PersistentAlert("SuperStructure", "${escapeJavaString(a.message)}", PersistentAlert.Level.${a.level});`,
  );

  const superFields = [
    ...superAlertFields,
    ...subInfos.map(
      (info) =>
        `  private final ${info.className} ${info.varName};\n  private ${info.requestEnum} ${info.requestField} = ${info.requestEnum}.${info.sub.fsm.initialRequest};`,
    ),
    ...(superUsesZones
      ? [
          "  private final FieldZones fieldZones;",
          "  private final Supplier<Pose2d> poseSupplier;",
        ]
      : []),
  ].join("\n");

  const ctorParams = [
    ...subInfos.map((info) => `${info.className} ${info.varName}`),
    ...(superUsesZones ? ["FieldZones fieldZones", "Supplier<Pose2d> poseSupplier"] : []),
  ].join(", ");
  const ctorAssigns = [
    ...subInfos.map((info) => `    this.${info.varName} = ${info.varName};`),
    ...(superUsesZones
      ? [
          "    this.fieldZones = fieldZones;",
          "    this.poseSupplier = poseSupplier;",
        ]
      : []),
  ].join("\n");

  const superBindings = project.superstructure.bindings
    .map((b) => `    bindRequest(RobotRequest.${b.request}, RobotState.${b.entryState});`)
    .join("\n");

  const superGetters = subInfos
    .map(
      (info) => `  public ${info.requestEnum} get${info.className}Request() {
    return ${info.requestField};
  }

  public boolean is${info.className}AtGoal() {
    return ${info.varName}.atGoal();
  }`,
    )
    .join("\n\n");

  const allAtGoalExpr =
    subInfos.length > 0
      ? subInfos.map((info) => `is${info.className}AtGoal()`).join(" && ")
      : "true";
  const allAtGoalMethod = `  public boolean allSubsystemsAtGoal() {\n    return ${allAtGoalExpr};\n  }`;

  const superStructureJava = `package ${pkg}.subsystems.superstructure;

${superImports}

/** Overall robot state machine coordinating subsystems. */
public class SuperStructure extends SuperStructureBase<RobotRequest, RobotState> {
${superFields ? "\n" + superFields + "\n" : ""}
  public SuperStructure(${ctorParams}) {
    super(
        "Subsystems/SuperStructure",
        RobotState.class,
        RobotState.${project.superstructure.initialState},
        RobotRequest.${project.superstructure.initialRequest});
${ctorAssigns ? ctorAssigns + "\n" : ""}
${superStates}

${superBindings}
    generalFsm.validateComplete();
  }
${superGetters ? "\n" + superGetters + "\n" : ""}
${allAtGoalMethod}
}
`;

  const autoWired = Boolean(project.autonomous?.enabled && hasDrivetrain);
  const keepAutoRules = Boolean(project.autonomous?.keepAutomationsInAuto ?? true);

  // SuperStructureCommands.java (continuous button, sensor, or zone priorities)
  const continuousPilotEntries = project.controls.pilotPriority.filter((entry) => {
    if (entry.source === "sensor") {
      return entry.sensorTrigger === "whileTrue" || entry.sensorTrigger === "whileFalse" || !entry.sensorTrigger;
    }
    if (entry.source === "zone") {
      return entry.zoneTrigger === "inZone" || !entry.zoneTrigger;
    }
    return Boolean(entry.button);
  });
  const edgeEntries = project.controls.pilotPriority.filter(
    (entry) =>
      (entry.source === "sensor" &&
        (entry.sensorTrigger === "onTrue" || entry.sensorTrigger === "onFalse")) ||
      (entry.source === "zone" &&
        (entry.zoneTrigger === "enteredZone" || entry.zoneTrigger === "leftZone")),
  );

  const usedParamNames = new Set<string>();
  const pilotParams = continuousPilotEntries.map((entry, idx) => {
    const suffix =
      entry.source === "sensor"
        ? "Sensor"
        : entry.source === "zone"
          ? "Zone"
          : "Button";
    const base = `${toCamelCase(entry.request)}${suffix}`;
    let paramName = base;
    if (usedParamNames.has(paramName)) {
      paramName = `${base}${idx + 1}`;
    }
    usedParamNames.add(paramName);
    return { ...entry, paramName };
  });

  const manageParamsSignature = [
    "SuperStructure superStructure",
    ...pilotParams.map((p) => `BooleanSupplier ${p.paramName}`),
  ].join(", ");

  let requestSelectionBody = `              RobotRequest request = RobotRequest.${project.superstructure.initialRequest};`;
  if (pilotParams.length > 0) {
    const branches = pilotParams
      .map(
        (p, idx) =>
          `              ${idx === 0 ? "if" : "} else if"} (${p.paramName}.getAsBoolean()) {\n                request = RobotRequest.${p.request};`,
      )
      .join("\n");
    requestSelectionBody = `              RobotRequest request;\n${branches}\n              } else {\n                request = RobotRequest.${project.superstructure.initialRequest};\n              }`;
  }

  let autoManageBranch = "";
  if (autoWired) {
    const autoParams = pilotParams.filter((p) => p.source === "sensor" || p.source === "zone");
    if (keepAutoRules && autoParams.length > 0) {
      const autoIf = autoParams
        .map(
          (p, idx) =>
            `                ${idx === 0 ? "if" : "} else if"} (${p.paramName}.getAsBoolean()) {\n                  superStructure.setRequest(RobotRequest.${p.request});`,
        )
        .join("\n");
      autoManageBranch = `              if (DriverStation.isAutonomous()) {\n${autoIf}\n                }\n                return;\n              }\n`;
    } else {
      autoManageBranch =
        "              if (DriverStation.isAutonomous()) {\n                return;\n              }\n";
    }
  }

  const manageCommandsImports = [
    "import edu.wpi.first.wpilibj2.command.Command;",
    "import edu.wpi.first.wpilibj2.command.Commands;",
    `import ${pkg}.Constants.RobotRequest;`,
    `import ${pkg}.subsystems.superstructure.SuperStructure;`,
    ...(autoWired ? ["import edu.wpi.first.wpilibj.DriverStation;"] : []),
    ...(pilotParams.length > 0 ? ["import java.util.function.BooleanSupplier;"] : []),
  ]
    .sort()
    .join("\n");

  const autoRequestMethod = autoWired
    ? `

  /** Sends an autonomous request to the SuperStructure, optionally waiting until mechanisms reach their goals. */
  public static Command autoRequest(
      SuperStructure superStructure,
      RobotRequest request,
      boolean waitForGoal,
      double timeoutSec) {
    Command apply =
        Commands.runOnce(() -> superStructure.setRequest(request))
            .withName("AutoRequest_" + request.name());
    if (!waitForGoal) {
      return apply;
    }
    return apply
        .andThen(
            Commands.waitUntil(superStructure::allSubsystemsAtGoal)
                .withTimeout(${formatDouble(1)}))
        .withName("AutoRequest_" + request.name());
  }`
    : "";

  const superStructureCommandsJava = `package ${pkg}.commands;

${manageCommandsImports}

/** Driver commands for the SuperStructure. */
public final class SuperStructureCommands {
  private SuperStructureCommands() {}

  /** Evaluates the pilot's button and sensor priorities every cycle and forwards the winning request. */
  public static Command manageRequests(${manageParamsSignature}) {
    return Commands.run(
            () -> {
${autoManageBranch}${requestSelectionBody}
              superStructure.setRequest(request);
            },
            superStructure)
        .withName("Requests by pilot");
  }${autoRequestMethod.replace(formatDouble(1), "timeoutSec")}
}
`;

  // RobotContainer.java (wires LEDs & Rumble triggers via inState — zero coupling inside subsystems!)
  const usesLeds = projectUsesLedArbiter(project);
  const usesRumble = projectUsesRumbleArbiter(project);
  const usesTriggers = edgeEntries.length > 0;

  const containerImportSet = new Set<string>([
    "import edu.wpi.first.wpilibj.smartdashboard.SmartDashboard;",
    "import edu.wpi.first.wpilibj2.command.Command;",
    "import edu.wpi.first.wpilibj2.command.Commands;",
    "import edu.wpi.first.wpilibj2.command.button.CommandXboxController;",
    `import ${pkg}.commands.SuperStructureCommands;`,
    `import ${pkg}.subsystems.superstructure.SuperStructure;`,
    "import org.ciprix.CiprixSettings;",
  ]);

  if (usesTriggers) {
    containerImportSet.add("import edu.wpi.first.wpilibj2.command.button.Trigger;");
  }

  for (const info of subInfos) {
    const vendorIo = getVendorIoClassName(info.sub.name, info.sub.motor.vendor);
    containerImportSet.add(`import ${pkg}.subsystems.${info.subPkg}.${info.className};`);
    containerImportSet.add(`import ${pkg}.subsystems.${info.subPkg}.${info.className}Commands;`);
    containerImportSet.add(`import ${pkg}.subsystems.${info.subPkg}.${info.className}IO;`);
    containerImportSet.add(`import ${pkg}.subsystems.${info.subPkg}.${info.className}IOSim;`);
    containerImportSet.add(`import ${pkg}.subsystems.${info.subPkg}.${vendorIo};`);
  }

  const ledInfos = ledSubs.map((s) => {
    const className = toPascalCase(s.name);
    const varName = toCamelCase(className);
    const subPkg = toPackageSegment(s.name);
    containerImportSet.add(`import ${pkg}.subsystems.${subPkg}.${className};`);
    return { sub: s, className, varName, subPkg };
  });

  if (usesLeds) {
    containerImportSet.add("import edu.wpi.first.wpilibj.util.Color;");
    containerImportSet.add(`import ${pkg}.subsystems.leds.LedArbiter;`);
    containerImportSet.add(`import ${pkg}.subsystems.leds.LedArbiter.LedPattern;`);
    containerImportSet.add(`import ${pkg}.subsystems.leds.LedArbiter.LedSpec;`);
  }
  if (usesRumble) {
    containerImportSet.add(`import ${pkg}.subsystems.rumble.RumbleArbiter;`);
    containerImportSet.add(`import ${pkg}.subsystems.rumble.RumbleArbiter.TargetController;`);
  }

  // Collect subsystem state LED / rumble trigger lines
  const effectTriggerLines: string[] = [];
  let needRobotStateImport = false;

  for (const info of subInfos) {
    for (const st of info.sub.fsm.states) {
      for (const act of st.actions) {
        if (act.kind === "leds") {
          containerImportSet.add(
            `import ${pkg}.subsystems.${info.subPkg}.${info.className}Constants.${info.stateEnum};`,
          );
          const secColor = act.secondaryColorHex ? hexToJavaColor(act.secondaryColorHex) : "null";
          const specExpr = `new LedSpec(${ledPatternToJavaEnum(act.pattern)}, ${hexToJavaColor(act.colorHex)}, ${secColor}, ${formatDouble(act.periodSec)})`;
          const ownerKey = `${info.sub.id}:${st.name}:${act.id}`;
          if (act.when === "exit") {
            effectTriggerLines.push(
              `    ${info.varName}\n        .inState(${info.stateEnum}.${st.name})\n        .onFalse(\n            LedArbiter.holdEffect(\n                    ledArbiter, "${act.ledSubsystemId}", "${ownerKey}", ${act.priority}, ${specExpr})\n                .withTimeout(${formatDouble(Math.max(0.25, act.periodSec))}));`,
            );
          } else {
            effectTriggerLines.push(
              `    ${info.varName}\n        .inState(${info.stateEnum}.${st.name})\n        .whileTrue(\n            LedArbiter.holdEffect(\n                ledArbiter, "${act.ledSubsystemId}", "${ownerKey}", ${act.priority}, ${specExpr}));`,
            );
          }
        } else if (act.kind === "rumble") {
          containerImportSet.add(
            `import ${pkg}.subsystems.${info.subPkg}.${info.className}Constants.${info.stateEnum};`,
          );
          const triggerMethod = act.when === "exit" ? "onFalse" : "onTrue";
          const pilotExpr = renderRumbleSupplierExpr("rumbleArbiter.pilot()", act);
          const copilotExpr = renderRumbleSupplierExpr("rumbleArbiter.copilot()", act);
          effectTriggerLines.push(
            `    ${info.varName}\n        .inState(${info.stateEnum}.${st.name})\n        .${triggerMethod}(\n            rumbleArbiter.trigger(\n                ${controllerToJavaEnum(act.controller)},\n                ${act.priority},\n                ${pilotExpr},\n                ${copilotExpr}));`,
          );
        }
      }
    }
  }

  for (const [stateName, effects] of Object.entries(project.superstructure.stateEffects ?? {})) {
    for (const eff of effects) {
      if (eff.kind === "leds") {
        needRobotStateImport = true;
        const secColor = eff.secondaryColorHex ? hexToJavaColor(eff.secondaryColorHex) : "null";
        const specExpr = `new LedSpec(${ledPatternToJavaEnum(eff.pattern)}, ${hexToJavaColor(eff.colorHex)}, ${secColor}, ${formatDouble(eff.periodSec)})`;
        const ownerKey = `super:${stateName}:${eff.id}`;
        if (eff.when === "exit") {
          effectTriggerLines.push(
            `    superStructure\n        .inState(RobotState.${stateName})\n        .onFalse(\n            LedArbiter.holdEffect(\n                    ledArbiter, "${eff.ledSubsystemId}", "${ownerKey}", ${eff.priority}, ${specExpr})\n                .withTimeout(${formatDouble(Math.max(0.25, eff.periodSec))}));`,
          );
        } else {
          effectTriggerLines.push(
            `    superStructure\n        .inState(RobotState.${stateName})\n        .whileTrue(\n            LedArbiter.holdEffect(\n                ledArbiter, "${eff.ledSubsystemId}", "${ownerKey}", ${eff.priority}, ${specExpr}));`,
          );
        }
      } else if (eff.kind === "rumble") {
        needRobotStateImport = true;
        const triggerMethod = eff.when === "exit" ? "onFalse" : "onTrue";
        const pilotExpr = renderRumbleSupplierExpr("rumbleArbiter.pilot()", eff);
        const copilotExpr = renderRumbleSupplierExpr("rumbleArbiter.copilot()", eff);
        effectTriggerLines.push(
          `    superStructure\n        .inState(RobotState.${stateName})\n        .${triggerMethod}(\n            rumbleArbiter.trigger(\n                ${controllerToJavaEnum(eff.controller)},\n                ${eff.priority},\n                ${pilotExpr},\n                ${copilotExpr}));`,
        );
      }
    }
  }

  const visionCameras = hasDrivetrain && dt?.vision.enabled ? dt.vision.cameras : [];
  const hasVision = visionCameras.length > 0;

  if (edgeEntries.length > 0) {
    containerImportSet.add(`import ${pkg}.Constants.RobotRequest;`);
  }
  if (needRobotStateImport) {
    containerImportSet.add(`import ${pkg}.Constants.RobotState;`);
  }
  if (hasDrivetrain) {
    containerImportSet.add(`import ${pkg}.subsystems.drive.Drive;`);
  }
  if (hasZones) {
    containerImportSet.add(`import ${pkg}.field.FieldZones;`);
  }
  if (autoWired) {
    containerImportSet.add(`import ${pkg}.auto.AutonomousSetup;`);
    if (usesTriggers && !keepAutoRules) {
      containerImportSet.add("import edu.wpi.first.wpilibj.DriverStation;");
    }
  }
  if (hasVision) {
    containerImportSet.add("import edu.wpi.first.apriltag.AprilTagFieldLayout;");
    containerImportSet.add("import edu.wpi.first.apriltag.AprilTagFields;");
    containerImportSet.add("import org.ciprix.vision.AprilTagVision;");
    containerImportSet.add("import org.ciprix.vision.VisionFilter;");
    containerImportSet.add("import org.ciprix.vision.VisionIO;");
    containerImportSet.add("import org.ciprix.vision.VisionIOLimelight;");
  }

  const containerFields = [
    ...(hasDrivetrain ? ["  private final Drive drive;"] : []),
    ...(hasZones ? ["  private final FieldZones fieldZones = new FieldZones();"] : []),
    ...(hasVision ? ["  private final AprilTagVision vision;"] : []),
    ...(usesLeds ? ["  private final LedArbiter ledArbiter = new LedArbiter();"] : []),
    ...(usesRumble ? ["  private final RumbleArbiter rumbleArbiter;"] : []),
    ...ledInfos.map((info) => `  private final ${info.className} ${info.varName};`),
    ...subInfos.map((info) => `  private final ${info.className} ${info.varName};`),
    `  private final SuperStructure superStructure;`,
    ...(autoWired ? ["  private final AutonomousSetup autonomousSetup;"] : []),
  ].join("\n");

  const visionCamCalls = visionCameras
    .map(
      (cam) =>
        `            .withCamera(\n                "${escapeJavaString(cam.name)}",\n                switch (CiprixSettings.getMode()) {\n                  case REAL, SIM ->\n                      new VisionIOLimelight("${escapeJavaString(cam.ntName)}", drive::getRotation);\n                  case REPLAY -> new VisionIO() {};\n                },\n                ${formatDouble(cam.stdDevFactor)})`,
    )
    .join("\n");

  const containerInits = [
    ...(hasDrivetrain ? ["    drive = new Drive();"] : []),
    ...(hasVision
      ? [
          `    vision =\n        new AprilTagVision(drive::addVisionMeasurement, drive::getPose, drive::getRobotVelocity)\n            .withFilter(\n                new VisionFilter()\n                    .field(AprilTagFieldLayout.loadField(AprilTagFields.k2026RebuiltWelded)))\n${visionCamCalls};`,
        ]
      : []),
    ...(usesRumble ? ["    rumbleArbiter = new RumbleArbiter(pilot, copilot);"] : []),
    ...ledInfos.map(
      (info) =>
        `    ${info.varName} = new ${info.className}("${info.sub.id}", ledArbiter);`,
    ),
    ...subInfos.map((info) => {
      const vendorIo = getVendorIoClassName(info.sub.name, info.sub.motor.vendor);
      return `    ${info.varName} =
        new ${info.className}(
            switch (CiprixSettings.getMode()) {
              case REAL -> new ${vendorIo}();
              case SIM -> new ${info.className}IOSim();
              case REPLAY -> new ${info.className}IO() {};
            });`;
    }),
  ].join("\n");

  const renderExtraCondition = (cond: PilotCondition): string => {
    let base = "false";
    if (cond.kind === "button") {
      base = `pilot.${xboxButtonToJavaMethod(cond.button, cond.triggerThreshold)}.getAsBoolean()`;
    } else if (cond.kind === "sensor") {
      const info = subInfoById.get(cond.sensorOwnerId);
      const sensor = info?.sub.sensors?.find((s) => s.id === cond.sensorId);
      if (info && sensor) {
        base = `${info.varName}.${getSensorGetterName(sensor)}()`;
      }
    } else if (cond.kind === "zone") {
      const zEnum = zoneEnumById.get(cond.zoneId);
      if (zonesWired && zEnum) {
        base = `fieldZones.inZone(ZoneId.${zEnum}, drive.getPose())`;
      }
    }
    return cond.negated ? `!${base}` : base;
  };

  const superArgs = [
    ...subInfos.map((info) => info.varName),
    ...(superUsesZones ? ["fieldZones", "drive::getPose"] : []),
  ].join(", ");

  const pilotArgsList = [
    "superStructure",
    ...pilotParams.map((p) => {
      const andExprs = (p.andConditions ?? []).map(renderExtraCondition);
      let primaryBool = "false";
      let isSimpleButton = false;

      if (p.source === "sensor") {
        const info = p.sensorOwnerId ? subInfoById.get(p.sensorOwnerId) : undefined;
        const sensor = info?.sub.sensors?.find((s) => s.id === p.sensorId);
        if (info && sensor) {
          const getterCall = `${info.varName}.${getSensorGetterName(sensor)}()`;
          primaryBool = p.sensorTrigger === "whileFalse" ? `!${getterCall}` : getterCall;
        }
      } else if (p.source === "zone") {
        const zEnum = p.zoneId ? zoneEnumById.get(p.zoneId) : undefined;
        if (zonesWired && zEnum) {
          primaryBool = `fieldZones.inZone(ZoneId.${zEnum}, drive.getPose())`;
        }
      } else {
        isSimpleButton = andExprs.length === 0;
        primaryBool = `pilot.${xboxButtonToJavaMethod(p.button ?? "a", p.triggerThreshold)}.getAsBoolean()`;
      }

      if (isSimpleButton) {
        return `pilot.${xboxButtonToJavaMethod(p.button ?? "a", p.triggerThreshold)}`;
      }
      const combined = [primaryBool, ...andExprs].join(" && ");
      return `() -> ${combined}`;
    }),
  ];
  const pilotArgs = pilotArgsList.join(", ");

  const edgeTriggerLines = edgeEntries
    .map((entry) => {
      let getterCall: string | null = null;
      let method: "onTrue" | "onFalse" = "onTrue";

      if (entry.source === "sensor") {
        const info = entry.sensorOwnerId ? subInfoById.get(entry.sensorOwnerId) : undefined;
        const sensor = info?.sub.sensors?.find((s) => s.id === entry.sensorId);
        if (!info || !sensor) return null;
        getterCall = `${info.varName}.${getSensorGetterName(sensor)}()`;
        method = entry.sensorTrigger === "onFalse" ? "onFalse" : "onTrue";
      } else if (entry.source === "zone") {
        const zEnum = entry.zoneId ? zoneEnumById.get(entry.zoneId) : undefined;
        if (!zonesWired || !zEnum) return null;
        getterCall = `fieldZones.inZone(ZoneId.${zEnum}, drive.getPose())`;
        method = entry.zoneTrigger === "leftZone" ? "onFalse" : "onTrue";
      }
      if (!getterCall) return null;

      const andExprs = (entry.andConditions ?? []).map(renderExtraCondition);
      const actionCmd =
        andExprs.length > 0
          ? `Commands.runOnce(() -> { if (${andExprs.join(" && ")}) { superStructure.setRequest(RobotRequest.${entry.request}); } })`
          : `Commands.runOnce(() -> superStructure.setRequest(RobotRequest.${entry.request}))`;
      const triggerCondition =
        autoWired && !keepAutoRules
          ? `!DriverStation.isAutonomous() && (${getterCall})`
          : getterCall;
      return `    new Trigger(() -> ${triggerCondition}).${method}(${actionCmd});`;
    })
    .filter(Boolean)
    .join("\n");

  if (pilotArgs.includes("ZoneId.") || edgeTriggerLines.includes("ZoneId.")) {
    containerImportSet.add(`import ${pkg}.field.FieldZones.ZoneId;`);
  }

  const defaultCommands = subInfos
    .map(
      (info) =>
        `    ${info.varName}.setDefaultCommand(${info.className}Commands.defaultCommand(superStructure, ${info.varName}));`,
    )
    .join("\n");

  const copilotBindings = project.controls.copilotOverrides
    .map((ov) => {
      const info = subInfoById.get(ov.subsystemId);
      if (!info) return null;
      const cmdMethod = requestToCommandMethod(ov.request);
      return `    copilot.${xboxButtonToJavaMethod(ov.button, ov.triggerThreshold)}.whileTrue(${info.className}Commands.${cmdMethod}(${info.varName}));`;
    })
    .filter(Boolean)
    .join("\n");

  const selfTests = subInfos
    .filter((info) => info.sub.selfTest.enabled)
    .map(
      (info) =>
        `    SmartDashboard.putData("SelfTest/${info.className}", ${info.varName}.selfTestCommand());`,
    )
    .join("\n");

  const driveBindingLines: string[] = [];
  if (hasDrivetrain && dt) {
    if (zonesWired) {
      driveBindingLines.push(
        "    drive.setZoneHooks(fieldZones::applyDriveModifiers, () -> fieldZones.periodic(drive.getPose()));",
      );
    }
    driveBindingLines.push(
      `    drive.setDefaultCommand(\n        drive.driveTeleopCommand(\n            () -> -pilot.getLeftY(),\n            () -> -pilot.getLeftX(),\n            () -> -pilot.getRightX(),\n            () -> -pilot.getRightY()));`,
    );
    if (dt.controls.resetGyroButton) {
      driveBindingLines.push(
        `    pilot.${xboxButtonToJavaMethod(dt.controls.resetGyroButton)}.onTrue(Commands.runOnce(drive::zeroHeading).ignoringDisable(true));`,
      );
    }
    if (dt.controls.toggleFieldOrientedButton) {
      driveBindingLines.push(
        `    pilot.${xboxButtonToJavaMethod(dt.controls.toggleFieldOrientedButton)}.onTrue(Commands.runOnce(drive::toggleFieldOriented).ignoringDisable(true));`,
      );
    }
  }
  const driveBlock =
    driveBindingLines.length > 0 ? "\n" + driveBindingLines.join("\n") : "";

  const driveContextComment =
    !hasDrivetrain && project.features.driveContextStub
      ? "\n    // DriveContext stub enabled: integrate Phoenix Tuner X or YAGSL drivetrain here."
      : "";

  const effectBlock =
    effectTriggerLines.length > 0 ? "\n" + effectTriggerLines.join("\n") : "";

  const edgeBlock = edgeTriggerLines ? "\n" + edgeTriggerLines : "";

  const robotContainerJava = `package ${pkg};

${Array.from(containerImportSet).sort().join("\n")}

/** Robot structure: subsystems, driver and co-driver buttons, autonomous. */
public class RobotContainer {
${containerFields}

  private final CommandXboxController pilot = new CommandXboxController(0);
  private final CommandXboxController copilot = new CommandXboxController(1);

  public RobotContainer() {
${containerInits ? containerInits + "\n" : ""}    superStructure = new SuperStructure(${superArgs});${autoWired ? "\n    autonomousSetup = new AutonomousSetup(superStructure);" : ""}

    configureBindings();
  }

  private void configureBindings() {${driveBlock}
    superStructure.setDefaultCommand(
        SuperStructureCommands.manageRequests(${pilotArgs}));
${defaultCommands ? "\n" + defaultCommands : ""}
${copilotBindings ? "\n" + copilotBindings : ""}${edgeBlock}${effectBlock}
${selfTests ? "\n" + selfTests : ""}${driveContextComment}
  }

  public Command getAutonomousCommand() {
    return ${autoWired ? "autonomousSetup.getAutonomousCommand()" : "Commands.none()"};
  }
}
`;

  const wpilibPrefs =
    JSON.stringify(
      {
        enableCppIntellisense: false,
        currentLanguage: "java",
        projectYear: String(project.project.year),
        teamNumber: project.project.teamNumber,
      },
      null,
      4,
    ) + "\n";

  const rootProjectName =
    project.project.name.replace(/[^A-Za-z0-9_-]/g, "-") || "first-robot";
  const settingsGradle = `import org.gradle.internal.os.OperatingSystem

pluginManagement {
    repositories {
        mavenLocal()
        gradlePluginPortal()
        String frcYear = '${project.project.year}'
        File frcHome
        if (OperatingSystem.current().isWindows()) {
            String publicFolder = System.getenv('PUBLIC')
            if (publicFolder == null) {
                publicFolder = "C:\\\\Users\\\\Public"
            }
            def homeRoot = new File(publicFolder, "wpilib")
            frcHome = new File(homeRoot, frcYear)
        } else {
            def userFolder = System.getProperty("user.home")
            def homeRoot = new File(userFolder, "wpilib")
            frcHome = new File(homeRoot, frcYear)
        }
        def frcHomeMaven = new File(frcHome, 'maven')
        maven {
            name = 'frcHome'
            url = frcHomeMaven
        }
    }
}

Properties props = System.getProperties();
props.setProperty("org.gradle.internal.native.headers.unresolved.dependencies.ignore", "true");

rootProject.name = '${rootProjectName}'

def ciprixDir = file('../..')
def ciprixSettings = new File(ciprixDir, 'settings.gradle')
if (ciprixSettings.exists() && ciprixSettings.text.contains("rootProject.name = 'ciprix'")) {
    includeBuild(ciprixDir)
}
`;

  return [
    { path: `${javaBase}/Main.java`, content: mainJava },
    { path: `${javaBase}/Constants.java`, content: constantsJava },
    { path: `${javaBase}/Robot.java`, content: robotJava },
    { path: `${javaBase}/subsystems/superstructure/SuperStructure.java`, content: superStructureJava },
    { path: `${javaBase}/commands/SuperStructureCommands.java`, content: superStructureCommandsJava },
    { path: `${javaBase}/RobotContainer.java`, content: robotContainerJava },
    { path: `.wpilib/wpilib_preferences.json`, content: wpilibPrefs },
    { path: `settings.gradle`, content: settingsGradle },
    { path: `ciprix-project.json`, content: JSON.stringify(project, null, 2) + "\n" },
  ];
}
