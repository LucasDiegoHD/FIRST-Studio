import type { SubsystemConfig } from "../../schema/ciprix-project";
import { formatDouble, toPackageSegment, toPascalCase } from "../java-utils";
import type { GeneratedFile } from "../subsystems/roller";

export function generateLedArbiterFile(basePackage: string): GeneratedFile {
  const pkgPrefix = basePackage.replace(/\./g, "/");
  const fullPkg = `${basePackage}.subsystems.leds`;

  const content = `package ${fullPkg};

import edu.wpi.first.wpilibj.util.Color;
import edu.wpi.first.wpilibj2.command.Command;
import edu.wpi.first.wpilibj2.command.Commands;
import java.util.Comparator;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;

/** Coordinates LED pattern requests across subsystems and SuperStructure by priority. */
public class LedArbiter {
  public enum LedPattern {
    SOLID,
    BLINK,
    BREATHE,
    RAINBOW,
    PROGRESS_BAR,
    ALLIANCE
  }

  public record LedSpec(LedPattern pattern, Color primary, Color secondary, double periodSec) {}

  private record Entry(String ownerId, int priority, long seq, LedSpec spec) {}

  private final Map<String, Map<String, Entry>> entriesByTarget = new HashMap<>();
  private long seqCounter = 0L;

  public void request(String targetLedId, String ownerId, int priority, LedSpec spec) {
    entriesByTarget
        .computeIfAbsent(targetLedId, (ignored) -> new HashMap<>())
        .put(ownerId, new Entry(ownerId, priority, ++seqCounter, spec));
  }

  public void clear(String targetLedId, String ownerId) {
    Map<String, Entry> targetMap = entriesByTarget.get(targetLedId);
    if (targetMap != null) {
      targetMap.remove(ownerId);
    }
  }

  public Optional<LedSpec> resolve(String targetLedId) {
    Map<String, Entry> targetMap = entriesByTarget.get(targetLedId);
    if (targetMap == null || targetMap.isEmpty()) {
      return Optional.empty();
    }
    return targetMap.values().stream()
        .max(
            Comparator.comparingInt(Entry::priority)
                .thenComparingLong(Entry::seq))
        .map(Entry::spec);
  }

  public static Command holdEffect(
      LedArbiter arbiter, String targetLedId, String ownerId, int priority, LedSpec spec) {
    return Commands.startEnd(
            () -> arbiter.request(targetLedId, ownerId, priority, spec),
            () -> arbiter.clear(targetLedId, ownerId))
        .ignoringDisable(true);
  }
}
`;

  return {
    path: `src/main/java/${pkgPrefix}/subsystems/leds/LedArbiter.java`,
    content,
  };
}

export function generateLedSubsystemFiles(
  subsystem: SubsystemConfig,
  basePackage: string,
): GeneratedFile[] {
  const leds = subsystem.leds;
  if (!leds) return [];

  const className = toPascalCase(subsystem.name);
  const subPkg = toPackageSegment(subsystem.name);
  const pkgPrefix = basePackage.replace(/\./g, "/");
  const baseDir = `src/main/java/${pkgPrefix}/subsystems/${subPkg}`;
  const fullSubPkg = `${basePackage}.subsystems.${subPkg}`;
  const constantsClass = `${className}Constants`;
  const arbiterImport = `${basePackage}.subsystems.leds.LedArbiter`;

  const hwConstLines =
    leds.driver === "candle"
      ? `  public static final int CANDLE_ID = ${leds.canId ?? 30};\n  public static final int LED_COUNT = ${leds.ledCount};`
      : `  public static final int PWM_PORT = ${leds.pwmPort ?? 0};\n  public static final int LED_COUNT = ${leds.ledCount};`;

  const constantsContent = `package ${fullSubPkg};

/** ${className} LED hardware constants generated by FIRST Studio. */
public final class ${constantsClass} {
  private ${constantsClass}() {}

${hwConstLines}
  public static final double DEFAULT_PERIOD_SEC = 1.0;
}
`;

  if (leds.driver === "candle") {
    const busName = (leds.canBus ?? "").trim();
    const canBusArg = busName && busName !== "rio" ? `new CANBus("${busName}")` : "new CANBus()";

    const candleSubsystem = `package ${fullSubPkg};

import com.ctre.phoenix6.CANBus;
import com.ctre.phoenix6.controls.RainbowAnimation;
import com.ctre.phoenix6.controls.SolidColor;
import com.ctre.phoenix6.controls.StrobeAnimation;
import com.ctre.phoenix6.hardware.CANdle;
import com.ctre.phoenix6.signals.RGBWColor;
import edu.wpi.first.wpilibj.DriverStation;
import edu.wpi.first.wpilibj.DriverStation.Alliance;
import edu.wpi.first.wpilibj.Timer;
import edu.wpi.first.wpilibj.util.Color;
import edu.wpi.first.wpilibj2.command.SubsystemBase;
import ${arbiterImport};
import ${arbiterImport}.LedPattern;
import ${arbiterImport}.LedSpec;
import java.util.Optional;

/** ${className} subsystem controlling a CTRE CANdle via {@link LedArbiter}. */
public class ${className} extends SubsystemBase {
  private final String targetId;
  private final LedArbiter arbiter;
  private final CANdle candle = new CANdle(${constantsClass}.CANDLE_ID, ${canBusArg});

  public ${className}(String targetId, LedArbiter arbiter) {
    this.targetId = targetId;
    this.arbiter = arbiter;
  }

  @Override
  public void periodic() {
    Optional<LedSpec> resolved = arbiter.resolve(targetId);
    if (resolved.isEmpty()) {
      applySolid(Color.kBlack);
      return;
    }

    LedSpec spec = resolved.get();
    double period = Math.max(0.05, spec.periodSec());
    double phase = (Timer.getFPGATimestamp() % period) / period;

    switch (spec.pattern()) {
      case SOLID -> applySolid(spec.primary());
      case BLINK -> {
        double hz = Math.min(500.0, Math.max(1.0, 1.0 / period));
        candle.setControl(
            new StrobeAnimation(0, ${constantsClass}.LED_COUNT - 1)
                .withColor(toRgbw(spec.primary()))
                .withFrameRate(hz)
                .withSlot(0));
      }
      case BREATHE -> {
        double scale = 0.5 - 0.5 * Math.cos(phase * 2.0 * Math.PI);
        applySolid(scaleColor(spec.primary(), scale));
      }
      case RAINBOW ->
          candle.setControl(
              new RainbowAnimation(0, ${constantsClass}.LED_COUNT - 1).withSlot(0));
      case PROGRESS_BAR -> {
        int litCount = (int) Math.round(phase * ${constantsClass}.LED_COUNT);
        if (litCount > 0) {
          candle.setControl(new SolidColor(0, litCount - 1).withColor(toRgbw(spec.primary())));
        }
        if (litCount < ${constantsClass}.LED_COUNT) {
          Color bg = spec.secondary() != null ? spec.secondary() : Color.kBlack;
          candle.setControl(
              new SolidColor(litCount, ${constantsClass}.LED_COUNT - 1).withColor(toRgbw(bg)));
        }
      }
      case ALLIANCE -> {
        Alliance alliance = DriverStation.getAlliance().orElse(Alliance.Blue);
        applySolid(alliance == Alliance.Red ? Color.kRed : Color.kBlue);
      }
    }
  }

  private void applySolid(Color color) {
    candle.setControl(
        new SolidColor(0, ${constantsClass}.LED_COUNT - 1).withColor(toRgbw(color)));
  }

  private static RGBWColor toRgbw(Color color) {
    return new RGBWColor(
        (int) Math.round(color.red * 255.0),
        (int) Math.round(color.green * 255.0),
        (int) Math.round(color.blue * 255.0),
        0);
  }

  private static Color scaleColor(Color color, double scale) {
    return new Color(color.red * scale, color.green * scale, color.blue * scale);
  }
}
`;
    return [
      { path: `${baseDir}/${constantsClass}.java`, content: constantsContent },
      { path: `${baseDir}/${className}.java`, content: candleSubsystem },
    ];
  }

  const pwmSubsystem = `package ${fullSubPkg};

import edu.wpi.first.wpilibj.AddressableLED;
import edu.wpi.first.wpilibj.AddressableLEDBuffer;
import edu.wpi.first.wpilibj.DriverStation;
import edu.wpi.first.wpilibj.DriverStation.Alliance;
import edu.wpi.first.wpilibj.Timer;
import edu.wpi.first.wpilibj.util.Color;
import edu.wpi.first.wpilibj2.command.SubsystemBase;
import ${arbiterImport};
import ${arbiterImport}.LedPattern;
import ${arbiterImport}.LedSpec;
import java.util.Optional;

/** ${className} subsystem controlling WPILib AddressableLEDs via {@link LedArbiter}. */
public class ${className} extends SubsystemBase {
  private final String targetId;
  private final LedArbiter arbiter;
  private final AddressableLED led = new AddressableLED(${constantsClass}.PWM_PORT);
  private final AddressableLEDBuffer buffer = new AddressableLEDBuffer(${constantsClass}.LED_COUNT);

  public ${className}(String targetId, LedArbiter arbiter) {
    this.targetId = targetId;
    this.arbiter = arbiter;
    led.setLength(buffer.getLength());
    led.setData(buffer);
    led.start();
  }

  @Override
  public void periodic() {
    Optional<LedSpec> resolved = arbiter.resolve(targetId);
    if (resolved.isEmpty()) {
      fillSolid(Color.kBlack);
      led.setData(buffer);
      return;
    }

    LedSpec spec = resolved.get();
    double period = Math.max(0.05, spec.periodSec());
    double phase = (Timer.getFPGATimestamp() % period) / period;

    switch (spec.pattern()) {
      case SOLID -> fillSolid(spec.primary());
      case BLINK -> {
        boolean on = phase < 0.5;
        Color off = spec.secondary() != null ? spec.secondary() : Color.kBlack;
        fillSolid(on ? spec.primary() : off);
      }
      case BREATHE -> {
        double scale = 0.5 - 0.5 * Math.cos(phase * 2.0 * Math.PI);
        fillSolid(new Color(spec.primary().red * scale, spec.primary().green * scale, spec.primary().blue * scale));
      }
      case RAINBOW -> {
        int firstHue = (int) Math.round(phase * 180.0);
        for (int i = 0; i < buffer.getLength(); i++) {
          int hue = (firstHue + (i * 180 / Math.max(1, buffer.getLength()))) % 180;
          buffer.setHSV(i, hue, 255, 160);
        }
      }
      case PROGRESS_BAR -> {
        int litCount = (int) Math.round(phase * buffer.getLength());
        Color bg = spec.secondary() != null ? spec.secondary() : Color.kBlack;
        for (int i = 0; i < buffer.getLength(); i++) {
          buffer.setLED(i, i < litCount ? spec.primary() : bg);
        }
      }
      case ALLIANCE -> {
        Alliance alliance = DriverStation.getAlliance().orElse(Alliance.Blue);
        fillSolid(alliance == Alliance.Red ? Color.kRed : Color.kBlue);
      }
    }

    led.setData(buffer);
  }

  private void fillSolid(Color color) {
    for (int i = 0; i < buffer.getLength(); i++) {
      buffer.setLED(i, color);
    }
  }
}
`;

  // Unused import guard for formatDouble not needed above
  void formatDouble;

  return [
    { path: `${baseDir}/${constantsClass}.java`, content: constantsContent },
    { path: `${baseDir}/${className}.java`, content: pwmSubsystem },
  ];
}
